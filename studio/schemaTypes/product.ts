import { defineArrayMember, defineField, defineType } from "sanity";

export default defineType({
  name: "product",
  title: "Producto",
  type: "document",
  groups: [
    { name: "customer", title: "Información para clientes", default: true },
    { name: "admin", title: "Administración interna" },
  ],
  fields: [
    defineField({ name: "name", title: "Nombre", type: "string", group: "customer", validation: (rule) => rule.required() }),
    defineField({ name: "slug", title: "URL del producto", type: "slug", group: "customer", options: { source: "name", maxLength: 96 }, validation: (rule) => rule.required() }),
    defineField({
      name: "category",
      title: "Categoría",
      type: "string",
      group: "customer",
      options: {
        list: [
          { title: "Skincare", value: "skincare" },
          { title: "Accesorios de Plata", value: "accesorios-plata" },
          { title: "Manillas de Oro", value: "manillas-oro" },
        ],
        layout: "radio",
      },
      validation: (rule) => rule.required(),
    }),
    defineField({ name: "shortDescription", title: "Descripción corta", type: "text", group: "customer", rows: 2, validation: (rule) => rule.required().max(180) }),
    defineField({ name: "description", title: "Descripción completa", type: "text", group: "customer", rows: 5, validation: (rule) => rule.required() }),
    defineField({ name: "price", title: "Precio en COP", type: "number", group: "customer", validation: (rule) => rule.required().integer().positive() }),
    defineField({ name: "reference", title: "Referencia comercial", type: "string", group: "customer", description: "SKU comercial opcional. No corresponde al ID interno del documento." }),
    defineField({
      name: "presentation",
      title: "Presentación",
      type: "string",
      group: "customer",
      hidden: ({ document }) => document?.category !== "skincare",
    }),
    defineField({
      name: "quantityOrVolume",
      title: "Cantidad o volumen",
      type: "string",
      group: "customer",
      hidden: ({ document }) => document?.category !== "skincare",
    }),
    defineField({
      name: "material",
      title: "Material verificado",
      description: "Déjalo vacío hasta contar con información confirmada.",
      type: "string",
      group: "customer",
      hidden: ({ document }) => document?.category === "skincare",
    }),
    defineField({
      name: "finish",
      title: "Color o acabado verificado",
      description: "Déjalo vacío hasta contar con información confirmada.",
      type: "string",
      group: "customer",
      hidden: ({ document }) => document?.category === "skincare",
    }),
    defineField({
      name: "measurements",
      title: "Medidas o dimensiones",
      type: "string",
      group: "customer",
      hidden: ({ document }) => document?.category === "skincare",
    }),
    defineField({
      name: "catalogAttributes",
      title: "Clasificación para filtros",
      description: "Completa únicamente atributos comprobados. Estos datos controlan los filtros públicos del catálogo y no deben inferirse de las fotografías.",
      type: "object",
      group: "customer",
      hidden: ({ document }) => document?.category === "skincare",
      fields: [
        defineField({
          name: "audience",
          title: "Público",
          type: "string",
          options: {
            list: [
              { title: "Mujer", value: "mujer" },
              { title: "Hombre", value: "hombre" },
              { title: "Unisex", value: "unisex" },
            ],
            layout: "radio",
          },
        }),
        defineField({
          name: "jewelryType",
          title: "Tipo de joya",
          type: "string",
          options: {
            list: [
              { title: "Anillo", value: "anillo" },
              { title: "Dije", value: "dije" },
              { title: "Argolla", value: "argolla" },
              { title: "Pulso", value: "pulso" },
              { title: "Topo", value: "topo" },
              { title: "Cadena", value: "cadena" },
              { title: "Arete", value: "arete" },
              { title: "Collar", value: "collar" },
              { title: "Pulsera", value: "pulsera" },
              { title: "Tobillera", value: "tobillera" },
              { title: "Ear cuff", value: "ear-cuff" },
            ],
          },
        }),
        defineField({
          name: "ringSizes",
          title: "Tallas de anillo",
          description: "Solo para anillos con tallas verificadas.",
          type: "array",
          of: [{ type: "string" }],
          hidden: ({ parent }) => parent?.jewelryType !== "anillo",
        }),
        defineField({
          name: "lengths",
          title: "Largos disponibles",
          description: "Incluye la unidad en cada valor, por ejemplo 45 cm.",
          type: "array",
          of: [{ type: "string" }],
          hidden: ({ parent }) => !["cadena", "pulso", "pulsera", "tobillera", "collar"].includes(parent?.jewelryType),
        }),
        defineField({
          name: "weaveType",
          title: "Tipo de tejido",
          type: "string",
          hidden: ({ parent }) => parent?.jewelryType !== "cadena",
        }),
        defineField({
          name: "motif",
          title: "Motivo o diseño",
          type: "string",
          hidden: ({ parent }) => parent?.jewelryType !== "dije",
        }),
        defineField({ name: "stone", title: "Piedra verificada", type: "string" }),
      ],
    }),
    defineField({
      name: "variants",
      title: "Variantes",
      description: "Úsalo solo cuando el cliente deba elegir, por ejemplo, talla, color o presentación.",
      type: "array",
      group: "customer",
      of: [
        defineArrayMember({
          type: "object",
          name: "variant",
          fields: [
            defineField({ name: "name", title: "Nombre", type: "string", validation: (rule) => rule.required() }),
            defineField({ name: "required", title: "Selección obligatoria", type: "boolean", initialValue: true }),
            defineField({
              name: "options",
              title: "Opciones",
              type: "array",
              of: [
                defineArrayMember({
                  type: "object",
                  name: "variantOption",
                  fields: [
                    defineField({ name: "label", title: "Nombre de la opción", type: "string", validation: (rule) => rule.required() }),
                  ],
                  preview: { select: { title: "label" } },
                }),
              ],
              validation: (rule) => rule.required().min(1),
            }),
          ],
          preview: { select: { title: "name", options: "options" }, prepare: ({ title, options }) => ({ title, subtitle: `${options?.length || 0} opciones` }) },
        }),
      ],
      validation: (rule) => rule.max(4),
    }),
    defineField({
      name: "images",
      title: "Fotografías",
      type: "array",
      group: "customer",
      of: [defineArrayMember({ type: "image", options: { hotspot: true }, fields: [defineField({ name: "alt", title: "Texto alternativo", type: "string", validation: (rule) => rule.required() })] })],
      validation: (rule) => rule.required().min(1).max(12),
    }),
    defineField({
      name: "stock",
      title: "Existencias",
      description: "Cantidad total disponible. En productos con inventario por variante se mantiene sincronizada con la suma de sus variantes.",
      type: "number",
      group: "admin",
      initialValue: 0,
      validation: (rule) => rule.integer().min(0),
    }),
    defineField({
      name: "purchaseEnabled",
      title: "Compra habilitada",
      description: "Permite pausar compras aunque existan unidades.",
      type: "boolean",
      group: "admin",
      initialValue: true,
    }),
    defineField({
      name: "variantInventory",
      title: "Existencias por variante",
      description: "Configuración técnica creada por el desarrollador. El panel de inventario solo permite cambiar sus cantidades.",
      type: "array",
      group: "admin",
      of: [
        defineArrayMember({
          type: "object",
          name: "variantInventoryLine",
          fields: [
            defineField({ name: "label", title: "Nombre visible", type: "string", validation: (rule) => rule.required() }),
            defineField({
              name: "optionIds",
              title: "IDs de opciones asociados",
              type: "array",
              of: [{ type: "string" }],
              validation: (rule) => rule.required().min(1),
            }),
            defineField({ name: "stock", title: "Existencias", type: "number", initialValue: 0, validation: (rule) => rule.required().integer().min(0) }),
          ],
          preview: { select: { title: "label", stock: "stock" }, prepare: ({ title, stock }) => ({ title, subtitle: `${stock ?? 0} unidades` }) },
        }),
      ],
    }),
    defineField({ name: "featured", title: "Producto destacado", type: "boolean", group: "admin", initialValue: false }),
    defineField({ name: "visible", title: "Visible en el sitio", type: "boolean", group: "admin", initialValue: true }),
    defineField({ name: "displayOrder", title: "Orden de aparición", type: "number", group: "admin", initialValue: 100, validation: (rule) => rule.integer().min(0) }),
    defineField({
      name: "legacyId",
      title: "ID de origen",
      description: "Identificador estable usado para migraciones idempotentes. No se muestra públicamente.",
      type: "string",
      group: "admin",
      readOnly: true,
    }),
    defineField({
      name: "migrationSource",
      title: "Origen de migración",
      type: "string",
      group: "admin",
      readOnly: true,
    }),
    defineField({
      name: "isDemo",
      title: "Contenido de demostración",
      description: "Permite identificar y reemplazar de forma controlada los datos ficticios.",
      type: "boolean",
      group: "admin",
      initialValue: false,
      readOnly: true,
    }),
  ],
  preview: {
    select: { title: "name", subtitle: "category", media: "images.0" },
  },
});
